"""
   -------------------------------------------------------------------------
   Source: FEBRACA Forms, the data behind cm_localities (shared/data/municipalities)
   Name: cm_municipalities
   Purpose: Fetches Brazil's 27 UFs and every municipality of each from the
       IBGE API, checked, so no list is ever typed by hand; and writes them as
       the per-UF files cm_localities loads.
   Context: Rebuilt the 27 data files of cm_localities when the service was
       renamed; run it again whenever IBGE creates or renames a municipality.
   Technique: fnFetchMunicipalities fetches and checks every UF before it
       returns, so a failure halfway never leaves old and new files mixed.
       IBGE gzips its answers even unasked, so the body is unpacked by its
       magic bytes, not by a header.
   Requirements:
       - Python 3.8+, standard library only.
       - Network access to servicodados.ibge.gov.br.

   Parameters:
       - bv_vUF: a UF's two letters, as IBGE writes them ('SP').
       - bv_dtNamesByUF: { 'SP': ['Adamantina', …], … }, as
         fnFetchMunicipalities returns it.
       - bv_vFolder: where vsWriteLocalitiesFiles writes; created when missing.
   Notes: Raises ValueError, naming the UF, when IBGE answers something
       unexpected, and OSError when it does not answer. The files are UTF-8
       with LF endings; an apostrophe is escaped for the JavaScript string
       ('Olho d\\'Água Grande'). Run directly, it is the generator:
       python cm_municipalities.py <folder> writes the 27 files; exit 0 when
       written, 1 when IBGE failed (nothing written), 2 for wrong input.

   Attribution:
       - Original Concept: IBGE, API de Localidades v1
         (https://servicodados.ibge.gov.br/api/docs/localidades)

   Version: 261030
   -------------------------------------------------------------------------
"""

import gzip
import json
import os
import sys
import urllib.request

cBaseURL = 'https://servicodados.ibge.gov.br/api/v1/localidades/estados'
cRequestTimeoutSeconds = 30
cUFCount = 27
cGzipMagic = b'\x1f\x8b'


def _fnFetchJSON(bv_vURL):
    with urllib.request.urlopen(bv_vURL, timeout=cRequestTimeoutSeconds) as sResponse:
        vBody = sResponse.read()
    if vBody[:2] == cGzipMagic:
        vBody = gzip.decompress(vBody)
    return json.loads(vBody.decode('utf-8'))


def fnFetchUFs():
    arAnswer = _fnFetchJSON(cBaseURL + '?orderBy=sigla')
    arUFs = [dtUF.get('sigla') for dtUF in arAnswer if isinstance(dtUF, dict)]
    arUFs = [vUF for vUF in arUFs if isinstance(vUF, str) and len(vUF) == 2]
    if len(arUFs) != cUFCount:
        raise ValueError('IBGE listed %d UFs, expected %d' % (len(arUFs), cUFCount))
    return arUFs


def fnFetchNames(bv_vUF):
    arAnswer = _fnFetchJSON('%s/%s/municipios?orderBy=nome' % (cBaseURL, bv_vUF))
    arNames = [dtCity.get('nome') for dtCity in arAnswer if isinstance(dtCity, dict)]
    if not arNames or not all(isinstance(vName, str) and vName.strip() for vName in arNames):
        raise ValueError('IBGE answered no usable names for %s' % bv_vUF)
    return arNames


def fnFetchMunicipalities():
    return {vUF: fnFetchNames(vUF) for vUF in fnFetchUFs()}


def _fnJSString(bv_vText):
    return "'" + bv_vText.replace('\\', '\\\\').replace("'", "\\'") + "'"


def fnLocalitiesFileText(bv_vUF, bv_arNames):
    return ('/* IBGE API de Localidades v1 - UF %s. Generated by cm_municipalities.py; never edit by hand. */\n'
            "cm_localities.vsRegisterMunicipalities('%s', [\n"
            '  %s\n'
            ']);\n') % (bv_vUF, bv_vUF, ','.join(_fnJSString(vName) for vName in bv_arNames))


def vsWriteLocalitiesFiles(bv_vFolder, bv_dtNamesByUF):
    os.makedirs(bv_vFolder, exist_ok=True)
    for vUF, arNames in bv_dtNamesByUF.items():
        with open(os.path.join(bv_vFolder, vUF + '.js'), 'w', encoding='utf-8', newline='\n') as sFile:
            sFile.write(fnLocalitiesFileText(vUF, arNames))


def fnMain():
    if len(sys.argv) != 2:
        print('Usage: python cm_municipalities.py <output folder>', file=sys.stderr)
        return 2

    try:
        dtNamesByUF = fnFetchMunicipalities()
    except (OSError, ValueError) as sError:
        print('Nothing written: %s' % sError, file=sys.stderr)
        return 1

    vsWriteLocalitiesFiles(sys.argv[1], dtNamesByUF)
    vTotal = sum(len(arNames) for arNames in dtNamesByUF.values())
    print('%d UFs, %d municipalities, written to %s' % (len(dtNamesByUF), vTotal, sys.argv[1]))
    return 0


if __name__ == '__main__':
    sys.exit(fnMain())


